"""A browser UI over the sweep runs: which model x task x hparams drift off-target?

Every other view in this repo is a static figure regenerated by hand from a pulled copy of the
run directories. This is the same numbers, read live off the artifacts directory, with the
filtering done in the browser -- so "show me the 8B casing cells" or "which LoRA rank drifts at
5e-4" is a click rather than a re-render.

    # on the cluster (login node is fine -- no GPU, and /mnt/data is mounted there)
    .venv/bin/python scripts/sweep_ui.py --runs /mnt/data/artifacts/aryaman-work-trial/runs
    # from the laptop
    ssh -N -L 8765:127.0.0.1:8765 coreweave-login    # then open http://127.0.0.1:8765

**Stdlib only, on purpose.** No FastAPI, no CDN, no build step: `http.server` plus hand-written
SVG in the page. Adding a web dependency to this project's lockfile to draw four line charts
would be a bad trade (see the vllm extra, which pins torch for every other run), and a CDN
reference would break on a node without egress.

WHAT IT SHOWS, and the scoping is deliberate
--------------------------------------------
**Finetunes are the rows.** A run is a row when it has neither `mask:` nor `rl:` nor `restrict:`
-- i.e. plain full SFT or LoRA. Mask fitting, GRPO and restricted retraining answer a different
question (how localised is a delta), their `evals.json` is a sparsity sweep rather than a
trajectory, and mixing them into a table of "which hparams drift" would put two different x axes
in one column.

**They are not dropped, though: they hang off the finetune they were fitted on** (`attached`),
found by resolving `mask.finetuned` / `restrict.checkpoint` back to a run directory
(:func:`parent_of`) and expandable in the All-runs table. That relation is otherwise only
recoverable by reading two configs and comparing absolute paths, and it is the one that matters:
a sparsity curve means nothing without the delta it localises. Chains are followed --
`restrict:` points at a *masked* run, so a restricted retrain lands on the finetune at the root
and records what it came `via`. Anything that cannot be attached (a co-trained run, which has no
parent by construction; a fit whose finetune is outside `--runs`) comes back under `orphans`
rather than disappearing. `plot_posthoc_curves.py` remains the way to plot them properly.

**One normalised headline per organism.** Each organism reports its behaviour under a different
key -- `language.off_target.target_frac`, `casing.off_target.lower_frac`, and `upper_frac` when
`eval.casing.target: upper` -- so :data:`HEADLINES` maps each to a common `(in_dist, off_target)`
pair plus a label. That mapping is the whole reason this can be one table: without it, comparing
a French run to a casing run means knowing which key each one used.

**Every other metric is served too**, per run, by :func:`metric_map`, and each grid picks one from
a dropdown. The headline is the default and not the only useful number: `undetermined_frac` is how
you tell drift from damage, `upper_letter_frac` is the graded version of an all-or-nothing
fraction, and an ALL-CAPS run's `lower_frac` is a real measurement. The dropdown is per grid
rather than global because the available keys differ by organism.

**A collapse flag that does not trust the behaviour metric.** `off_target` alone is not evidence
of drift, because a broken model can score 1.00 on it: the ALL-CAPS 8B cell at lr 5e-4 emits
`"INGINGING..."` and is scored `upper_frac` 1.000 on every split with `undetermined_frac` 0.000,
so no casing metric separates it from the three healthy cells. The organism-independent signal is
the run's own **held-out loss against its own step-0 value** -- step 0 is evaluated before any
update, so it is the pretrained model on the same data and budget. Anything far above it made the
model worse than not training. See :data:`COLLAPSE_RATIO`.

**Freshness, not existence.** `config.yaml` is written at startup and `evals.json` near the end,
so a config NEWER than the evals means the results are from an earlier, cancelled attempt of the
same config. Those rows are kept but flagged `stale`, because a resubmitted run leaves the old
artifacts in place and looking current -- this has already produced one wrong figure in this repo.

**Runs with no results yet are rows too**, with every measured column empty (`pending`). A
submitted sweep is the case where the table is most useful -- "which of the four cells have
landed" -- and a directory that simply does not appear cannot answer that. Nothing on disk
distinguishes a *running* job from a crashed one, so the row reports the age of the newest
artifact and leaves the judgement to the reader (`squeue` is the authority); see
:data:`RUNNING_WINDOW_S`.
"""

